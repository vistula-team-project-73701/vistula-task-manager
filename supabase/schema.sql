-- Run in a separate Supabase demonstration project containing test data only.
-- Safe to run again: it does not drop the table or delete existing tasks.
begin;
create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  title text not null check (length(btrim(title)) > 0),
  description text,
  completed boolean not null default false
);
alter table public.tasks enable row level security;
grant usage on schema public to anon;
revoke all on table public.tasks from anon;
grant select, insert, update, delete on table public.tasks to anon;
grant usage, select on sequence public.tasks_id_seq to anon;
drop policy if exists "Demo visitors can read tasks" on public.tasks;
create policy "Demo visitors can read tasks" on public.tasks for select to anon using (true);
drop policy if exists "Demo visitors can add tasks" on public.tasks;
create policy "Demo visitors can add tasks" on public.tasks for insert to anon with check (true);
drop policy if exists "Demo visitors can edit tasks" on public.tasks;
create policy "Demo visitors can edit tasks" on public.tasks for update to anon using (true) with check (true);
drop policy if exists "Demo visitors can delete tasks" on public.tasks;
create policy "Demo visitors can delete tasks" on public.tasks for delete to anon using (true);
notify pgrst, 'reload schema';
commit;
